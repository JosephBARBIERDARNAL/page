// Byte-to-glyph-name tables copied from veraPDF 1.30.2's
// `org.verapdf.pd.font.truetype.TrueTypePredefined`. These names are model
// data: glyph presence and width predicates compare them against embedded
// Type1, Type1C, and Type3 programs.

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum PredefinedEncoding {
    Standard,
    MacRoman,
    MacExpert,
    WinAnsi,
}

impl PredefinedEncoding {
    /// veraPDF's PDF `Encoding` model recognizes exactly these three names.
    /// `StandardEncoding` is deliberately absent: for a PDF encoding object,
    /// veraPDF treats it as empty and falls back to the font program.
    pub(crate) fn from_pdf_name(name: &[u8]) -> Option<Self> {
        match name {
            b"MacRomanEncoding" => Some(Self::MacRoman),
            b"MacExpertEncoding" => Some(Self::MacExpert),
            b"WinAnsiEncoding" => Some(Self::WinAnsi),
            _ => None,
        }
    }
}

